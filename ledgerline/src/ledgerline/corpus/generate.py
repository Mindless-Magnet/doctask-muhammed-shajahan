def _invoice(number: str, date: str, quantity: int, unit_price: float, po_ref: str) -> str:
    total = quantity * unit_price
    return (
        f"INVOICE {number}\n\n"
        f"Vendor: Northwind Logistics Group\n"
        f"Invoice date: {date}\n\n"
        f"Quantity: {quantity} pallets at a unit price of {unit_price:.2f} each.\n"
        f"Total due: {total:,.2f}\n"
        f"Purchase order reference: {po_ref}\n"
    )


def _purchase_order(number: str, amount: float, issued: str) -> str:
    return (
        f"PURCHASE ORDER {number}\n\n"
        f"Issued to Northwind Logistics Group on {issued}.\n"
        f"Committed amount: {amount:,.2f}\n"
    )


